#!/usr/bin/env bash
# Copies Ditto's own sources into the Chromium tree:
#   chromium/overlay/ditto -> src/ditto
#   agent/src              -> src/ditto/browser/resources/agent
source "$(dirname "$0")/common.sh"

[[ -d "$SRC_DIR" ]] || die "No Chromium checkout at $SRC_DIR; run scripts/fetch.sh"
log "Syncing overlay into $SRC_DIR/ditto"
# Replace wholesale so files deleted here disappear from the tree too.
rm -rf "$SRC_DIR/ditto"
cp -R "$DITTO_ROOT/chromium/overlay/ditto" "$SRC_DIR/ditto"

# Files Chromium needs in its own directories (e.g. grit wants .grdp parts
# next to their .grd).
(cd "$DITTO_ROOT/chromium/overlay" && find . -type f ! -path './ditto/*') |
  while IFS= read -r file; do
    mkdir -p "$SRC_DIR/$(dirname "$file")"
    cp "$DITTO_ROOT/chromium/overlay/$file" "$SRC_DIR/$file"
  done

agent_dst="$SRC_DIR/ditto/browser/resources/agent"
mkdir -p "$agent_dst"
cp -R "$DITTO_ROOT/agent/src/." "$agent_dst/"

# The WebUI build lists its TypeScript files explicitly.
{
  echo "# Generated by scripts/sync-overlay.sh. Do not edit."
  echo "ditto_agent_ts_files = ["
  (cd "$agent_dst/.." && find agent -name '*.ts' | LC_ALL=C sort | sed 's/.*/  "&",/')
  echo "]"
} > "$agent_dst/agent_files.gni"
